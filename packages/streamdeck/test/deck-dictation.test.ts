import { afterEach, expect, it, vi } from "vitest";
import { createDeckDictation } from "../src/deck-dictation.js";
import { createDeckAudio } from "../src/deck-audio.js";
import { createFrameInput } from "../src/frame-input.js";
import { dialButton } from "./support/deckReports.js";
import type { DeckSettings } from "../src/deck-settings.js";
const setup = () => {
  vi.useFakeTimers();
  let chunk!: (value: Uint8Array) => void;
  let captureError!: (code: number | null) => void;
  const kill = vi.fn();
  const spawn = vi.fn((command: string, args: readonly string[]) => { void command; void args; return { onData: (fn: typeof chunk) => { chunk = fn; }, onExit: (fn: typeof captureError) => { captureError = fn; }, kill }; });
  const channel = { voiceStart: vi.fn(), voiceAudio: vi.fn(), voiceStop: vi.fn(), say: vi.fn(), voiceStatus: vi.fn() };
  const settings: DeckSettings = { mic_id: "unplugged", speaker_id: null, default_view: "ticket", default_sort: "state", brightness: null, dim_after_seconds: 0, instance: null, alerts: {} };
  const audio = createDeckAudio({ settings: () => settings, devices: () => ({ mics: [{ id: "first", label: "First" }], speakers: [], instances: [] }), system: { run: vi.fn(), spawn } });
  const host = createDeckDictation({ channel: () => channel, capture: audio.capture, setTimer: setTimeout, clearTimer: (timer) => clearTimeout(timer as ReturnType<typeof setTimeout>) });
  const input = createFrameInput(host.input);
  return { host, input, spawn, kill, channel, chunk: (value: Uint8Array) => chunk(value), captureError: (code: number | null) => captureError(code) };
};
afterEach(() => vi.useRealTimers());
it("drives real HID hold through selected mic fallback, relay commit and tap to send settled text", () => {
  const h = setup(); h.host.focus("6046"); h.host.availability({ available: true, reason: null });
  h.input.handleReport(dialButton(2));
  vi.advanceTimersByTime(499); expect(h.spawn).not.toHaveBeenCalled();
  vi.advanceTimersByTime(1);
  expect(h.spawn).toHaveBeenCalledWith("parec", expect.arrayContaining(["--device=first"]));
  expect(h.channel.voiceStart).toHaveBeenCalledOnce();
  h.chunk(new Uint8Array(3200));
  expect(h.channel.voiceAudio).not.toHaveBeenCalled();
  h.host.started("voice1", null);
  expect(h.channel.voiceAudio).toHaveBeenCalledWith("voice1", expect.any(String));
  h.input.handleReport(dialButton(2, false));
  expect(h.kill).toHaveBeenCalledOnce();
  expect(h.channel.voiceStop).toHaveBeenCalledWith("voice1");
  h.host.voice("voice1", "partial", "run the");
  h.host.voice("voice1", "final", "run the tests");
  h.host.closed("voice1");
  h.input.handleReport(dialButton(2)); vi.advanceTimersByTime(50); h.input.handleReport(dialButton(2, false));
  expect(h.channel.say).toHaveBeenCalledExactlyOnceWith("6046", "run the tests");
  expect(h.channel.voiceStatus).toHaveBeenLastCalledWith("Dictation sent");
  h.host.disconnect();
});
it("commits a hold released before voice_start replies and clears text when focus changes", () => {
  const h = setup(); h.host.focus("A"); h.host.availability({ available: true, reason: null });
  h.input.handleReport(dialButton(2)); vi.advanceTimersByTime(500);
  h.chunk(new Uint8Array(3200)); h.input.handleReport(dialButton(2, false));
  expect(h.channel.voiceStop).not.toHaveBeenCalled();
  h.host.started("voice1", null); expect(h.channel.voiceStop).toHaveBeenCalledWith("voice1");
  h.host.voice("voice1", "final", "private draft");
  h.host.focus("B");
  h.input.handleReport(dialButton(2)); h.input.handleReport(dialButton(2, false));
  expect(h.channel.say).not.toHaveBeenCalled();
  h.host.voice("voice1", "final", "stale draft"); h.host.closed("voice1"); h.host.disconnect();
});
it("shows the actual unavailable reason and requires a focused ticket before capture", () => {
  const h = setup();
  h.input.handleReport(dialButton(2)); vi.advanceTimersByTime(500); h.input.handleReport(dialButton(2, false));
  expect(h.channel.voiceStatus).toHaveBeenLastCalledWith("Open a ticket before dictating");
  h.host.focus("A"); h.host.focus("A"); h.host.availability({ available: false, reason: "Provider key missing" });
  h.input.handleReport(dialButton(2)); vi.advanceTimersByTime(500); h.input.handleReport(dialButton(2, false));
  expect(h.channel.voiceStatus).toHaveBeenLastCalledWith("Provider key missing");
  h.host.availability({ available: false, reason: null });
  h.input.handleReport(dialButton(2)); vi.advanceTimersByTime(500); h.input.handleReport(dialButton(2, false));
  expect(h.channel.voiceStatus).toHaveBeenLastCalledWith("Voice unavailable");
  expect(h.spawn).not.toHaveBeenCalled(); h.host.disconnect();
});
it("stops recording on provider or capture failure and ignores unrelated controls", () => {
  const h = setup(); h.host.focus("A"); h.host.availability({ available: true, reason: null });
  h.input.handleReport(dialButton(1)); h.input.handleReport(dialButton(1, false));
  h.input.handleReport(dialButton(2)); vi.advanceTimersByTime(500); h.host.started("voice1", null);
  h.host.error("voice1", "Provider failed");
  expect(h.kill).toHaveBeenCalled(); expect(h.channel.voiceStatus).toHaveBeenLastCalledWith("Provider failed");
  h.input.handleReport(dialButton(2, false));
  h.input.handleReport(dialButton(2)); vi.advanceTimersByTime(500); h.host.started("voice2", null);
  h.captureError(1);
  expect(h.channel.voiceStatus).toHaveBeenLastCalledWith("Microphone capture failed (exit 1)");
  h.input.handleReport(dialButton(2, false)); h.host.disconnect();
});
it("closes a late session after disconnect and waits before opening another", () => {
  const h = setup(); h.host.focus("A"); h.host.availability({ available: true, reason: null });
  h.input.handleReport(dialButton(2)); vi.advanceTimersByTime(500);
  h.host.disconnect(); h.input.reset(); h.host.focus("B");
  h.input.handleReport(dialButton(2)); vi.advanceTimersByTime(500);
  expect(h.channel.voiceStart).toHaveBeenCalledTimes(1);
  expect(h.channel.voiceStatus).toHaveBeenLastCalledWith("Waiting for the previous voice session");
  h.host.started("old", null); expect(h.channel.voiceStop).toHaveBeenCalledWith("old");
  h.input.handleReport(dialButton(2, false)); h.host.disconnect();
});
it("retains partial-only text without sending it and suppresses stale frames after a focus change", () => {
  const h = setup(); h.host.focus("A"); h.host.availability({ available: true, reason: null });
  h.input.handleReport(dialButton(2)); vi.advanceTimersByTime(500); h.host.started("voice1", null);
  h.host.voice("voice1", "partial", "not settled");
  h.input.handleReport(dialButton(2, false));
  h.input.handleReport(dialButton(2)); h.input.handleReport(dialButton(2, false));
  expect(h.channel.say).not.toHaveBeenCalled();
  h.host.focus(null); h.host.focus("B");
  h.host.voice("voice1", "final", "old focus draft");
  h.input.handleReport(dialButton(2)); h.input.handleReport(dialButton(2, false));
  expect(h.channel.say).not.toHaveBeenCalled(); h.host.disconnect();
});
it("bounds status by UTF8 bytes and handles rejected starts and early provider closure", () => {
  const h = setup(); h.host.focus("A"); h.host.availability({ available: false, reason: "é".repeat(150) });
  h.input.handleReport(dialButton(2)); vi.advanceTimersByTime(500); h.input.handleReport(dialButton(2, false));
  expect(h.channel.voiceStatus).toHaveBeenLastCalledWith("é".repeat(100));
  h.host.availability({ available: true, reason: null });
  h.input.handleReport(dialButton(2)); vi.advanceTimersByTime(500); h.host.started(null, "Rejected");
  expect(h.channel.voiceStatus).toHaveBeenLastCalledWith("Rejected");
  h.input.handleReport(dialButton(2, false));
  h.input.handleReport(dialButton(2)); vi.advanceTimersByTime(500); h.host.started("voice2", null); h.host.closed("voice2");
  expect(h.kill).toHaveBeenCalledTimes(2);
  h.input.handleReport(dialButton(2, false)); h.host.disconnect();
  h.host.started(null, null);
});
it("a short physical press cannot send while a hold is still active", () => {
  const h = setup(); h.host.focus("A"); h.host.availability({ available: true, reason: null });
  h.input.handleReport(dialButton(2)); vi.advanceTimersByTime(500); h.host.started("voice1", null);
  h.host.voice("voice1", "final", "draft");
  h.host.input({ kind: "dial", index: 2, action: "press" });
  expect(h.channel.say).not.toHaveBeenCalled();
  h.host.input({ kind: "dial", index: 2, action: "turn", delta: 1 });
  h.host.disconnect();
});
