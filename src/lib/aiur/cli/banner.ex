defmodule Aiur.CLI.Banner do
  @moduledoc false
  # The guardrails-acknowledgement box `Aiur.CLI` prints when the flag is missing.

  @spec acknowledgement() :: String.t()
  def acknowledgement do
    lines = [
      "This Aiur implementation is a low key engineering preview.",
      "Codex will run without any guardrails.",
      "Aiur is not a supported product and is presented as-is.",
      "To proceed, start with `--i-understand-that-this-will-be-running-without-the-usual-guardrails` CLI argument"
    ]

    width = Enum.max(Enum.map(lines, &String.length/1))
    border = String.duplicate("─", width + 2)
    top = "╭" <> border <> "╮"
    bottom = "╰" <> border <> "╯"
    spacer = "│ " <> String.duplicate(" ", width) <> " │"

    content =
      [
        top,
        spacer
        | Enum.map(lines, fn line ->
            "│ " <> String.pad_trailing(line, width) <> " │"
          end)
      ] ++ [spacer, bottom]

    [
      IO.ANSI.red(),
      IO.ANSI.bright(),
      Enum.join(content, "\n"),
      IO.ANSI.reset()
    ]
    |> IO.iodata_to_binary()
  end
end
